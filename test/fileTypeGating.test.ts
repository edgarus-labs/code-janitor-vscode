import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { TextDocument, TextEditor, Uri, createContext, resetMock, state, window } from './helpers/vscodeMock';
import { cleanupFileGlob, isCleanupTarget, isSupportedFile, runCleanupOnUris, runFormatCommentsOnUris } from '../src/commands/cleanupCore';
import { registerEditorCommands } from '../src/commands/editorCommands';
import { FakeEngine, useFakeEngine } from './helpers/fakeEngine';

const folders: string[] = [];
let fake: FakeEngine;

beforeEach(() => {
  resetMock();
  fake = useFakeEngine({
    formatCommentText: (params) => ({
      text: String(params.text)
        .replace(/'(?=\S)/g, "' ")
        .replace(/\/\/(?=\S)/g, '// '),
    }),
  });
});

afterEach(() => {
  folders.splice(0).forEach((folder) => fs.rmSync(folder, { recursive: true, force: true }));
});

function otherFileTypes(on = true): void {
  state.configuration.set('codeJanitor.cleanup.includeOtherFileTypes', on);
}

/** A real folder holding `files`, for the checks that look at the disk (the T4 template next to a file). */
function folderWith(...files: string[]): string {
  const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'cj-t4-'));
  folders.push(folder);
  files.forEach((file) => fs.writeFileSync(path.join(folder, file), ''));

  return folder;
}

describe('file-type gating', () => {
  it('cleans no other file type while includeOtherFileTypes is off, whatever fileTypes says', () => {
    expect(isSupportedFile(Uri.file('/w/a.vb'))).toBe(false);
    expect(isSupportedFile(Uri.file('/w/a.cs'))).toBe(true);
  });

  it('cleans the languages fileTypes turns on', () => {
    otherFileTypes();
    state.configuration.set('codeJanitor.cleanup.fileTypes.vb', false);

    expect(isSupportedFile(Uri.file('/w/a.vb'))).toBe(false);
    expect(isSupportedFile(Uri.file('/w/a.ts'))).toBe(true);
    expect(isSupportedFile(Uri.file('/w/a.xml'))).toBe(true);
  });

  it('selects the other types with everythingElse', () => {
    otherFileTypes();
    state.configuration.set('codeJanitor.cleanup.fileTypes.everythingElse', false);

    expect(isSupportedFile(Uri.file('/w/notes.txt'))).toBe(false);
    expect(isSupportedFile(Uri.file('/w/a.json'))).toBe(true);
  });

  it('gates an untitled document by its language mode', () => {
    otherFileTypes();
    state.configuration.set('codeJanitor.cleanup.fileTypes.vb', false);
    const untitled = Uri.file('/w/Untitled-1');
    state.documents.push(new TextDocument(untitled, 'Module M\nEnd Module\n', 'vb'));

    expect(isSupportedFile(untitled)).toBe(false);
  });

  it('gates the layout rules of a Razor file with the HTML file type', async () => {
    otherFileTypes();
    state.configuration.set('codeJanitor.cleanup.formatRazorComponents', true);
    state.configuration.set('codeJanitor.cleanup.fileTypes.html', false);
    state.files.set('/w/Page.razor', '<p>a</p>   \n');

    expect(isSupportedFile(Uri.file('/w/Page.razor'))).toBe(false);
    expect(isCleanupTarget(Uri.file('/w/Page.razor'))).toBe(true);
    await runCleanupOnUris(createContext(), [Uri.file('/w/Page.razor')]);

    expect(state.files.get('/w/Page.razor')).toBe('<p>a</p>   \n');
  });

  it('skips a file generated by a T4 template, C# included, while excludeT4GeneratedCode is on', () => {
    otherFileTypes();
    const folder = folderWith('Model.tt', 'Model.cs', 'Model.vb', 'Other.cs');

    expect(isSupportedFile(Uri.file(path.join(folder, 'Model.cs')))).toBe(false);
    expect(isSupportedFile(Uri.file(path.join(folder, 'Model.vb')))).toBe(false);
    expect(isSupportedFile(Uri.file(path.join(folder, 'Other.cs')))).toBe(true);

    state.configuration.set('codeJanitor.cleanup.excludeT4GeneratedCode', false);

    expect(isSupportedFile(Uri.file(path.join(folder, 'Model.cs')))).toBe(true);
  });

  it('skips a Razor view generated by a T4 template', () => {
    state.configuration.set('codeJanitor.cleanup.formatRazorComponents', true);
    const folder = folderWith('View.tt', 'View.cshtml');

    expect(isCleanupTarget(Uri.file(path.join(folder, 'View.cshtml')))).toBe(false);
  });

  it('globs the extensions of the selected languages when everythingElse is off', () => {
    expect(cleanupFileGlob()).toBe('**/*.cs');
    otherFileTypes();

    expect(cleanupFileGlob()).toBe('**/*');

    state.configuration.set('codeJanitor.cleanup.fileTypes.everythingElse', false);
    state.configuration.set('codeJanitor.cleanup.fileTypes.css', false);
    const glob = cleanupFileGlob();

    expect(glob.startsWith('**/*.{cs,')).toBe(true);
    expect(glob.slice(6, -1).split(',')).toEqual(expect.arrayContaining(['cs', 'vb', 'ts', 'xaml', 'ps1', 'razor', 'cshtml']));
    expect(glob.slice(6, -1).split(',')).not.toContain('css');
  });
});

describe('cleanup of the other languages', () => {
  it('applies the steps of the language family', async () => {
    otherFileTypes();
    state.files.set('/w/a.xml', '<a>\n  <b/>\n\n</a>\n');
    state.files.set('/w/a.js', 'function f() {\n\n  return 1;\n}\n');

    await runCleanupOnUris(createContext(), [Uri.file('/w/a.xml'), Uri.file('/w/a.js')]);

    expect(state.files.get('/w/a.xml')).toBe('<a>\n  <b />\n</a>\n');
    expect(state.files.get('/w/a.js')).toBe('function f() {\n  return 1;\n}\n');
  });

  it('formats the comments of a Visual Basic file through the engine when formatComments is on', async () => {
    otherFileTypes();
    state.configuration.set('codeJanitor.cleanup.formatComments', true);
    state.files.set('/w/a.vb', "'comment\nModule M\nEnd Module\n");

    await runCleanupOnUris(createContext(), [Uri.file('/w/a.vb')]);

    expect(state.files.get('/w/a.vb')).toBe("' comment\nModule M\nEnd Module\n");
    const [request] = fake.requests('formatCommentText');
    expect(request.commentPrefix).toBe("'");
    expect(request.settings.formatComments).toBe(true);
  });

  it('leaves the comments of a Visual Basic file alone when formatComments is off', async () => {
    otherFileTypes();
    state.files.set('/w/a.vb', "'comment\nModule M\nEnd Module\n");

    await runCleanupOnUris(createContext(), [Uri.file('/w/a.vb')]);

    expect(state.files.get('/w/a.vb')).toBe("'comment\nModule M\nEnd Module\n");
    expect(fake.requests('formatCommentText')).toEqual([]);
  });
});

describe('Format Comments on the other languages', () => {
  it('formats the comments of the selected files whose comment prefix is known', async () => {
    state.files.set('/w/a.vb', "'vb\n");
    state.files.set('/w/a.ts', '//ts\n');
    state.files.set('/w/a.xml', '<!--xml-->\n');

    await runFormatCommentsOnUris([Uri.file('/w/a.vb'), Uri.file('/w/a.ts'), Uri.file('/w/a.xml')]);

    expect(state.files.get('/w/a.vb')).toBe("' vb\n");
    expect(state.files.get('/w/a.ts')).toBe('// ts\n');
    expect(state.files.get('/w/a.xml')).toBe('<!--xml-->\n');
    expect(fake.requests('formatCommentText').map((request) => request.commentPrefix)).toEqual(["'", '//']);
  });

  it('formats the comments of the active Visual Basic document', async () => {
    const document = new TextDocument(Uri.file('/w/a.vb'), "'vb\nModule M\nEnd Module\n", 'vb');
    state.documents.push(document);
    window.activeTextEditor = new TextEditor(document);
    registerEditorCommands(createContext());

    await state.commands.get('codeJanitor.formatComments')!();

    expect(document.getText()).toBe("' vb\nModule M\nEnd Module\n");
  });
});
