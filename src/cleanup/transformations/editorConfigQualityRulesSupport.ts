/**
 * The edit deleting a whole declaration with the doc comments directly above it, as full lines,
 * plus one blank line when the removal would otherwise leave two in a row or a blank line next to
 * a brace. `undefined` when the declaration shares a line with other code or contains
 * preprocessor directives.
 */
export function removeDeclarationEdit(source: string, declaration: Node): TextEdit | undefined {
  let first: Node = declaration;
  for (let previous = declaration.previousNamedSibling; previous?.type === 'comment'; previous = previous.previousNamedSibling) {
    const between = source.slice(previous.endIndex, first.startIndex);
    if (!/^[ \t]*\r?\n[ \t]*$/.test(between) || !previous.text.startsWith('///')) {
      break;
    }

    first = previous;
  }

  const start = lineStartAt(source, first.startIndex);
  const lineEnd = lineEndAt(source, declaration.endIndex);
  if (source.slice(start, first.startIndex).trim() || source.slice(declaration.endIndex, lineEnd).trim()) {
    return undefined;
  }

  const text = source.slice(first.startIndex, declaration.endIndex);
  if (/^[ \t]*#/m.test(text)) {
    return undefined;
  }

  let end = source[lineEnd] === '\r' ? lineEnd + 2 : lineEnd + 1;
  end = Math.min(end, source.length);

  const previousLine = start > 0 ? source.slice(lineStartAt(source, start - 1), start).trim() : '';
  const nextLineEnd = lineEndAt(source, end);
  const nextLine = source.slice(end, nextLineEnd).trim();
  const nextBreakEnd = Math.min(source[nextLineEnd] === '\r' ? nextLineEnd + 2 : nextLineEnd + 1, source.length);
  if (nextLine === '' && end < source.length && (previousLine === '' || previousLine.endsWith('{'))) {
    end = nextBreakEnd;
  } else if (previousLine === '' && start > 0 && nextLine.startsWith('}')) {
    return { start: lineStartAt(source, start - 1), end, text: '' };
  }

  return { start, end, text: '' };
}

