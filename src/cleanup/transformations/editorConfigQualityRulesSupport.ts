export const TYPE_DECLARATIONS = ['class_declaration', 'struct_declaration', 'record_declaration', 'interface_declaration', 'enum_declaration'];

/**
 * True when the parser could not make sense of a member declaration of the type (a tuple type as
 * a generic argument, for instance): its member list is then incomplete, so nothing may rely on it.
 */
export function hasBrokenMemberDeclarations(type: Node): boolean {
  return (type.childForFieldName('body')?.namedChildren ?? []).some(isRecoveredNode);
}

export function isRecordStruct(declaration: Node): boolean {
  return declaration.type === 'record_declaration' && declaration.children.some((child) => child.type === 'struct');
}

/** Visibility of a declaration from outside: Roslyn's resultant `SymbolVisibility`. */
export type Visibility = 'public' | 'internal' | 'private';

/**
 * The resultant visibility of a type or member: the most restrictive of its own accessibility and
 * that of each containing type. `protected` counts as public (derived types in other assemblies).
 */
export function resultantVisibility(declaration: Node): Visibility {
  let visibility: Visibility = 'public';
  for (let current: Node | null = declaration; current; current = current.parent) {
    if (ACCESSIBILITY_DECLARATIONS[current.type] !== true) {
      continue;
    }

    const own = declaredVisibility(current);
    if (own === 'private' || (own === 'internal' && visibility === 'public')) {
      visibility = own;
    }
  }

  return visibility;
}

const ACCESSIBILITY_DECLARATIONS: Record<string, true> = {
  class_declaration: true,
  struct_declaration: true,
  record_declaration: true,
  interface_declaration: true,
  enum_declaration: true,
  delegate_declaration: true,
  method_declaration: true,
  property_declaration: true,
  indexer_declaration: true,
  event_declaration: true,
  event_field_declaration: true,
  field_declaration: true,
  constructor_declaration: true,
  operator_declaration: true,
  conversion_operator_declaration: true,
};

/** The accessibility a declaration has on its own (Roslyn's `DeclaredAccessibility`), as a visibility group. */
export function declaredVisibility(declaration: Node): Visibility {
  const modifiers = new Set(modifiersOf(declaration).map((modifier) => modifier.text));
  if (modifiers.has('file')) {
    return 'private';
  }

  if (modifiers.has('public') || (modifiers.has('protected') && !modifiers.has('private'))) {
    return 'public';
  }

  if (modifiers.has('internal') || (modifiers.has('protected') && modifiers.has('private'))) {
    return 'internal';
  }

  if (modifiers.has('private')) {
    return 'private';
  }

  // No modifier: interface members are public, top-level types internal, everything else private.
  const container = containingTypeDeclaration(declaration);
  if (!container) {
    return 'internal';
  }

  return container.type === 'interface_declaration' ? 'public' : 'private';
}

/** The type declaration directly containing a member or nested type, if any. */
export function containingTypeDeclaration(node: Node): Node | undefined {
  const list = node.parent;
  if (list?.type !== 'declaration_list') {
    return undefined;
  }

  const owner = list.parent;

  return owner && TYPE_DECLARATIONS.includes(owner.type) ? owner : undefined;
}

/** The default modifier order of the .NET code style (`csharp_preferred_modifier_order`). */
const DEFAULT_MODIFIER_ORDER = [
  'public', 'private', 'protected', 'internal', 'file', 'static', 'extern', 'new', 'virtual', 'abstract',
  'sealed', 'override', 'readonly', 'unsafe', 'required', 'volatile', 'async',
];

/**
 * An edit adding `modifier` to a declaration at its place in `csharp_preferred_modifier_order`
 * (else the .NET default order); `partial` stays last. `before` is where a declaration without
 * modifiers gets it: the first token after its attributes.
 */
export function addModifierEdit(props: EditorConfigProperties, declaration: Node, modifier: string, before: Node): TextEdit {
  const preferred = effectiveEditorConfigValue(props, 'csharp_preferred_modifier_order')
    ?.split(',')
    .map((name) => name.trim());
  const order = preferred?.includes(modifier) ? preferred : DEFAULT_MODIFIER_ORDER;
  const rank = order.indexOf(modifier);
  const modifiers = modifiersOf(declaration);
  const after = modifiers.find((existing) => existing.text === 'partial' || order.indexOf(existing.text) > rank);
  if (after) {
    return { start: after.startIndex, end: after.startIndex, text: `${modifier} ` };
  }

  const last = modifiers[modifiers.length - 1];

  return last
    ? { start: last.endIndex, end: last.endIndex, text: ` ${modifier}` }
    : { start: before.startIndex, end: before.startIndex, text: `${modifier} ` };
}

