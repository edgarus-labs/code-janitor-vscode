/**
 * Shared infrastructure of the code-quality (CA) and IDE diagnostics without a code-style option
 * (see `editorConfigQualityRules.ts`): gating on the diagnostic's severity, generated code and
 * suppressions, option reading, framework checks and the syntactic type lookup the rules use to
 * prove what a receiver is.
 */

/** True when `diagnosticId` is enforced for the file and the file is not generated code. */
export function isRuleActive(context: RuleContext, diagnosticId: string, source: string): boolean {
  return isDiagnosticEnforced(context.props, diagnosticId) && !isGeneratedCode(context.props, source, context.fileName);
}

/**
 * Generated code, which the .NET analyzers do not report on: `generated_code = true`, a generated
 * file name, or a leading `<auto-generated>` comment.
 */
export function isGeneratedCode(props: EditorConfigProperties, source: string, fileName: string | undefined): boolean {
  const generated = props.get('generated_code')?.trim().toLowerCase();
  if (generated === 'true') {
    return true;
  }

  if (generated !== 'false' && fileName && /(?:\.designer|\.generated|\.g|\.g\.i)\.cs$|^TemporaryGeneratedFile_/i.test(fileName)) {
    return true;
  }

  const header = /^\uFEFF?(?:\s*(?:\/\/[^\n]*|\/\*[\s\S]*?\*\/))*/.exec(source)?.[0] ?? '';

  return /<auto-?generated/i.test(header);
}

/** The reporter message of a rule: `CA1822 line 12: ...`. */
export function describeDiagnostic(diagnosticId: string, source: string, index: number, message: string): string {
  return `${diagnosticId} line ${lineNumberAt(source, index)}: ${message}`;
}

/**
 * A `dotnet_code_quality` option of a rule, with the .NET precedence: the rule's own setting, then
 * its category's, then the one for all rules.
 */
export function readCodeQualityOption(props: EditorConfigProperties, diagnosticId: string, option: string): string | undefined {
  const category = SUPPORTED_DIAGNOSTICS[diagnosticId]?.category;
  const value =
    props.get(`dotnet_code_quality.${diagnosticId}.${option}`) ??
    (category ? props.get(`dotnet_code_quality.${category}.${option}`) : undefined) ??
    props.get(`dotnet_code_quality.${option}`);

  return value?.trim().toLowerCase();
}

