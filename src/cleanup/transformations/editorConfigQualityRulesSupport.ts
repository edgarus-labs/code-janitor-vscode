/** Removes whitespace, `global::` and a trailing nullable `?` from a type as written. */
export function normalizeType(text: string): string {
  return text.replace(/\s+/g, '').replace(/global::/g, '').replace(/\?$/, '');
}

/** `System.Collections.Generic.List<int>` -> `List`; `int[]` -> `int[]`. */
export function simpleTypeName(type: string): string {
  if (type.endsWith(']')) {
    return type;
  }

  const withoutArguments = type.replace(/<.*$/, '');

  return withoutArguments.slice(withoutArguments.lastIndexOf('.') + 1);
}

/** True when the type as written has type arguments: `List<int>`. */
export function isGenericType(type: string): boolean {
  return /^[^<]+<.+>$/.test(type);
}

/**
 * Looks up the declared type of simple expressions from the file's syntax: literals, object and
 * array creation, and names (locals, parameters, fields and properties of the enclosing type)
 * declared with an explicit type, or with `var` and one of those initializers. Anything whose
 * declaration or scope cannot be pinned down syntactically yields `undefined`.
 */
export class DeclaredTypes {
  private readonly declaredTypeNames: ReadonlySet<string>;

  constructor(
    private readonly model: SourceModel,
    projectTypeNames: ReadonlySet<string> = new Set()
  ) {
    this.declaredTypeNames = new Set([...model.types.map((type) => type.name), ...projectTypeNames]);
  }

  /** True when the file or project declares a type with this simple name (so a BCL name may not mean the BCL type). */
  declaresType(name: string): boolean {
    return this.declaredTypeNames.has(name);
  }

  typeOf(expression: Node, depth = 0): string | undefined {
    const node = unwrapParentheses(expression);
    switch (node.type) {
      case 'string_literal':
      case 'verbatim_string_literal':
      case 'raw_string_literal':
      case 'interpolated_string_expression':
        return 'string';
      case 'character_literal':
        return 'char';
      case 'object_creation_expression': {
        const type = node.childForFieldName('type');

        return type ? normalizeType(type.text) : undefined;
      }
      case 'array_creation_expression': {
        const type = node.namedChildren.find((child) => child.type === 'array_type');

        return type ? normalizeType(type.text).replace(/\[[^\]]*\]/g, (rank) => `[${rank.replace(/[^,]/g, '')}]`) : undefined;
      }
      case 'identifier':
        return depth > 2 ? undefined : this.typeOfName(node.text, node.startIndex, depth);
      case 'member_access_expression': {
        const receiver = node.childForFieldName('expression');
        const name = node.childForFieldName('name');
        if (receiver?.type !== 'this_expression' || name?.type !== 'identifier') {
          return undefined;
        }

        const type = typeAt(this.model, node.startIndex);
        const member = type ? this.fieldOrProperty(type, name.text) : undefined;

        return member ? this.symbolType(member, depth) : undefined;
      }
      default:
        return undefined;
    }
  }

  /** The declared type of a simple name at `offset`. */
  typeOfName(name: string, offset: number, depth = 0): string | undefined {
    const symbol = this.symbolAt(name, offset);

    return symbol ? this.symbolType(symbol, depth) : undefined;
  }

  /**
   * The type a simple name was declared with explicitly, as written without whitespace (keeping a
   * nullable `?`); `undefined` for `var` or an unknown declaration.
   */
  declaredTypeText(name: string, offset: number): string | undefined {
    const text = this.symbolAt(name, offset)?.declaredType?.replace(/\s+/g, '');

    return text && text !== 'var' ? text : undefined;
  }

  /** The local, parameter, field or property a simple name at `offset` refers to, when that is certain. */
  private symbolAt(name: string, offset: number): DeclaredSymbol | undefined {
    const local = this.localDeclaration(name, offset);
    if (local !== undefined) {
      return local ?? undefined;
    }

    for (let type = typeAt(this.model, offset); type; type = type.parent) {
      if (type.memberNames.has(name)) {
        return this.fieldOrProperty(type, name);
      }

      // An inherited member of the same name would hide an outer type's member.
      if (type.hasBaseList || type.isPartial) {
        return undefined;
      }
    }

    return undefined;
  }

  /**
   * The innermost local, parameter or range variable named `name` in scope at `offset`;
   * `undefined` when there is none, `null` when one exists whose scope is not known precisely.
   */
  localDeclaration(name: string, offset: number): DeclaredSymbol | undefined | null {
    let best: DeclaredSymbol | undefined;
    for (const symbol of this.model.symbols) {
      // Primary constructor parameters are in scope in the whole type, like its members.
      const primaryParameter = symbol.category === 'parameter' && symbol.owner !== undefined && TYPE_DECLARATIONS.includes(symbol.owner.type);
      if (
        symbol.name !== name ||
        primaryParameter ||
        (symbol.category !== 'local' && symbol.category !== 'parameter' && symbol.category !== 'range') ||
        !symbol.region ||
        !spans(symbol.region, offset, offset)
      ) {
        continue;
      }

      if (!symbol.regionPrecise) {
        return null;
      }

      if (!best || (best.region && symbol.region.startIndex >= best.region.startIndex)) {
        best = symbol;
      }
    }

    return best;
  }

  private fieldOrProperty(type: TypeInfo, name: string): DeclaredSymbol | undefined {
    if (type.isPartial) {
      return undefined;
    }

    const members = this.model.symbols.filter((symbol) => symbol.category === 'member' && symbol.type === type && symbol.name === name);

    return members.length === 1 && (members[0].kind === 'field' || members[0].kind === 'property') ? members[0] : undefined;
  }

  private symbolType(symbol: DeclaredSymbol, depth: number): string | undefined {
    const declared = symbol.declaredType ? normalizeType(symbol.declaredType) : undefined;
    if (declared !== 'var') {
      return declared || undefined;
    }

    // `var name = <initializer>;`
    const declarator = symbol.nameNode.parent;
    const initializer = declarator?.type === 'variable_declarator'
      ? declarator.namedChildren.find((child) => child.type === 'equals_value_clause')?.namedChildren[0]
      : undefined;

    return initializer ? this.typeOf(initializer, depth + 1) : undefined;
  }
}

export function unwrapParentheses(node: Node): Node {
  let current = node;
  while (current.type === 'parenthesized_expression' && current.namedChildren.length === 1) {
    current = current.namedChildren[0];
  }

  return current;
}

/** The expression `node` is part of once parentheses around it are skipped. */
export function parentSkippingParentheses(node: Node): { parent: Node | null; child: Node } {
  let child = node;
  let parent = node.parent;
  while (parent?.type === 'parenthesized_expression') {
    child = parent;
    parent = parent.parent;
  }

  return { parent, child };
}

/** True when `node` is inside a lambda or anonymous method (which may be an expression tree). */
export function isInsideLambda(node: Node, stop?: Node): boolean {
  for (let current = node.parent; current && current !== stop; current = current.parent) {
    if (current.type === 'lambda_expression' || current.type === 'anonymous_method_expression') {
      return true;
    }
  }

  return false;
}

/** True when `node` is inside an attribute (its arguments are persisted to metadata). */
export function isInsideAttribute(node: Node): boolean {
  for (let current = node.parent; current; current = current.parent) {
    if (current.type === 'attribute_list') {
      return true;
    }
  }

  return false;
}

/** The value of a C# string literal token with a single character, or `undefined`. */
export function singleCharacterOf(literal: Node): string | undefined {
  const text = literal.text;
  let body: string;
  if (literal.type === 'string_literal' && /^"[\s\S]*"$/.test(text) && !text.startsWith('"""')) {
    body = unescapeRegular(text.slice(1, -1)) ?? '';
  } else if (literal.type === 'verbatim_string_literal' && /^@"[\s\S]*"$/.test(text)) {
    body = text.slice(2, -1).replace(/""/g, '"');
  } else {
    return undefined;
  }

  return body.length === 1 ? body : undefined;
}

const SIMPLE_ESCAPES: Record<string, string> = {
  "'": "'", '"': '"', '\\': '\\', '0': '\0', a: '\x07', b: '\b', f: '\f', n: '\n', r: '\r', t: '\t', v: '\v', e: '\x1b',
};

function unescapeRegular(body: string): string | undefined {
  let result = '';
  for (let i = 0; i < body.length; i++) {
    const c = body[i];
    if (c !== '\\') {
      result += c;
      continue;
    }

    const next = body[i + 1];
    if (next === undefined) {
      return undefined;
    }

    if (SIMPLE_ESCAPES[next] !== undefined) {
      result += SIMPLE_ESCAPES[next];
      i++;
    } else if (next === 'u' && /^[0-9a-fA-F]{4}$/.test(body.slice(i + 2, i + 6))) {
      result += String.fromCharCode(parseInt(body.slice(i + 2, i + 6), 16));
      i += 5;
    } else if (next === 'U' && /^[0-9a-fA-F]{8}$/.test(body.slice(i + 2, i + 10))) {
      result += String.fromCodePoint(parseInt(body.slice(i + 2, i + 10), 16));
      i += 9;
    } else if (next === 'x') {
      const hex = /^[0-9a-fA-F]{1,4}/.exec(body.slice(i + 2))?.[0];
      if (!hex) {
        return undefined;
      }

      result += String.fromCharCode(parseInt(hex, 16));
      i += 1 + hex.length;
    } else {
      return undefined;
    }
  }

  return result;
}

/** A C# character literal for `c`. */
export function charLiteral(c: string): string {
  switch (c) {
    case "'":
      return "'\\''";
    case '\\':
      return "'\\\\'";
    case '\0':
      return "'\\0'";
    case '\n':
      return "'\\n'";
    case '\r':
      return "'\\r'";
    case '\t':
      return "'\\t'";
  }

  const code = c.charCodeAt(0);
  if (code < 0x20 || code === 0x7f || (code >= 0x80 && code <= 0x9f) || (code >= 0xd800 && code <= 0xdfff) || /\s/.test(c) && c !== ' ') {
    return `'\\u${code.toString(16).padStart(4, '0')}'`;
  }

  return `'${c}'`;
}
