interface PragmaDirective {
  readonly offset: number;
  readonly disable: boolean;
  /** Upper-cased diagnostic ids; empty for every warning. */
  readonly ids: readonly string[];
}

/** `#pragma warning disable/restore` directives and `[SuppressMessage]` attributes of a file. */
export class Suppressions {
  private readonly pragmas: PragmaDirective[] = [];

  constructor(source: string) {
    for (const trivia of lex(source).trivia) {
      if (trivia.type !== 'preproc_pragma') {
        continue;
      }

      const match = /^#\s*pragma\s+warning\s+(disable|restore)\b([^\r\n]*)/.exec(source.slice(trivia.start, trivia.end));
      if (match) {
        const ids = match[2]
          .replace(/\/\/.*$/, '')
          .split(',')
          .map((id) => id.trim().toUpperCase())
          .filter(Boolean);
        this.pragmas.push({ offset: trivia.start, disable: match[1] === 'disable', ids });
      }
    }
  }

  /** True when `diagnosticId` is suppressed at `node` (by a pragma, or an attribute on it or a containing declaration). */
  isSuppressed(diagnosticId: string, node: Node): boolean {
    return this.isSuppressedAt(diagnosticId, node.startIndex) || hasSuppressMessageAttribute(node, diagnosticId);
  }

  isSuppressedAt(diagnosticId: string, offset: number): boolean {
    const id = diagnosticId.toUpperCase();
    let disabled = false;
    for (const pragma of this.pragmas) {
      if (pragma.offset >= offset) {
        break;
      }

      if (pragma.ids.length === 0 || pragma.ids.includes(id)) {
        disabled = pragma.disable;
      }
    }

    return disabled;
  }
}

function hasSuppressMessageAttribute(node: Node, diagnosticId: string): boolean {
  const pattern = new RegExp(`"${diagnosticId}\\b`, 'i');
  for (let current: Node | null = node; current; current = current.parent) {
    for (const attribute of attributesOf(current)) {
      if (/^(?:[\w.]+\.)?SuppressMessage(?:Attribute)?$/.test(attributeName(attribute)) && pattern.test(attribute.text)) {
        return true;
      }
    }
  }

  return false;
}

/** The attributes applied to a declaration (not to its return value or parameters). */
export function attributesOf(declaration: Node): Node[] {
  return declaration.namedChildren
    .filter((child) => child.type === 'attribute_list' && !/^\[\s*(?:return|param|assembly|module)\s*:/.test(child.text))
    .flatMap((list) => list.namedChildren.filter((child) => child.type === 'attribute'));
}

/** An attribute's name as written, without the `Attribute` suffix and type arguments. */
export function attributeName(attribute: Node): string {
  const name = (attribute.childForFieldName('name') ?? attribute.namedChild(0))?.text ?? attribute.text;

  return name.replace(/\s+/g, '').replace(/<.*$/, '').replace(/Attribute$/, '');
}

/** The simple name of an attribute: `System.ObsoleteAttribute` -> `Obsolete`. */
export function attributeSimpleName(attribute: Node): string {
  return attributeName(attribute).split('.').pop() ?? '';
}

/** True when the declaration or one of its containing types carries `[Obsolete]`. */
export function isOnObsoleteChain(declaration: Node): boolean {
  for (let current: Node | null = declaration; current; current = current.parent) {
    if (attributesOf(current).some((attribute) => attributeSimpleName(attribute) === 'Obsolete')) {
      return true;
    }
  }

  return false;
}

