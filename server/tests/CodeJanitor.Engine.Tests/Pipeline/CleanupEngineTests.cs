    private static JsonObject Defaults() => CleanupSettingsDefaults.Create();

    private static CleanupRequest Request(Action<JsonObject>? configure = null, IReadOnlyCollection<string>? excluded = null, IReadOnlyList<LineRange>? changed = null)
    {
        var user = TestbedOff();
        configure?.Invoke(user);

        return new CleanupRequest(user, excluded ?? [], changed);
    }

    /// <summary>The defaults with every boolean off, so only the steps under test act.</summary>
