    private static void WritePolicy(Document document, string json)
    {
        var directory = Path.GetDirectoryName(document.FilePath)!;
        Directory.CreateDirectory(directory);
        File.WriteAllText(Path.Combine(directory, ".codejanitor"), json);
    }

    private static Document CreateDocument(string text, string? editorConfig = null, Workspace? workspace = null, IEnumerable<AnalyzerReference>? analyzerReferences = null)
    {
        var directory = Path.Combine(Root, Guid.NewGuid().ToString("N"));
        var projectId = ProjectId.CreateNewId();
        var filePath = Path.Combine(directory, "Sample.cs");
        var solution = (workspace ?? new AdhocWorkspace(HostAnalyzers.HostServices)).CurrentSolution.AddProject(ProjectInfo.Create(
            projectId,
            VersionStamp.Create(),
            "Sample",
            "Sample",
            LanguageNames.CSharp,
            filePath: Path.Combine(directory, "Sample.csproj"),
            compilationOptions: new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary),
            metadataReferences: [MetadataReference.CreateFromFile(typeof(object).Assembly.Location), MetadataReference.CreateFromFile(typeof(Enumerable).Assembly.Location), MetadataReference.CreateFromFile(Path.Combine(Path.GetDirectoryName(typeof(object).Assembly.Location)!, "System.Runtime.dll"))],
            analyzerReferences: analyzerReferences));
        var configPath = Path.Combine(directory, ".editorconfig");
        solution = solution.AddAnalyzerConfigDocument(DocumentId.CreateNewId(projectId), ".editorconfig", SourceText.From(editorConfig ?? "root = true\n"), filePath: configPath);
        var documentId = DocumentId.CreateNewId(projectId);
        solution = solution.AddDocument(DocumentInfo.Create(documentId, "Sample.cs", loader: TextLoader.From(TextAndVersion.Create(SourceText.From(text), VersionStamp.Create(), filePath)), filePath: filePath));

        return solution.GetDocument(documentId)!;
    }

    private static async Task<string> TextAsync(CleanupOutcome outcome)
    {
        var document = outcome.Solution.Projects.Single().Documents.Single();

        return (await document.GetTextAsync()).ToString();
    }

    private sealed class TextStep(string name, CleanupStage stage, int order, Func<string, string> transform) : ICleanupStep
    {
        public string Name => name;

        public string? RuleId => name;

        public CleanupStage Stage => stage;

        public int Order => order;

        public bool IsEnabled(IEffectiveSettings settings) => true;

        public async Task<Solution> ApplyAsync(Document document, IEffectiveSettings settings, CancellationToken cancellationToken)
        {
            var text = await document.GetTextAsync(cancellationToken);

            return document.WithText(SourceText.From(transform(text.ToString()), text.Encoding)).Project.Solution;
        }
    }

    /// <summary>A workspace that, like <c>MSBuildWorkspace</c>, cannot change the name or folders of a document.</summary>
    private sealed class DocumentInfoReadOnlyWorkspace() : Workspace(HostAnalyzers.HostServices, WorkspaceKind.Host)
    {
        public override bool CanApplyChange(ApplyChangesKind feature) => feature != ApplyChangesKind.ChangeDocumentInfo;
    }
