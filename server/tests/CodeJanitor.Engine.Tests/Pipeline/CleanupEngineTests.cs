    private const string ShiftingSource = "class C\n{\n    int Get(bool open)\n    {\n        if (open)\n            return 1;\n        return 0;\n    }\n\n    private int legacyValue;\n}\n";
    private const string ShiftingEditorConfig = "root = true\n[*.cs]\ncsharp_prefer_braces = true:warning\nend_of_line = lf\ndotnet_diagnostic.CJT0072.severity = warning\n";

    [Theory]
    [InlineData(10, true)]
    [InlineData(2, false)]
    public async Task ChangedLines_AnUnresolvedDiagnostic_IsFilteredByTheLineItHadBeforeTheFixesMovedIt(int legacyLine, bool reported)
    {
        var document = CreateDocument(ShiftingSource, ShiftingEditorConfig, analyzerReferences: [new AnalyzerImageReference([new Diagnostics.LegacyFieldAnalyzer("CJT0072", "Performance")])]);

        var outcome = await new CleanupEngine([new RoslynRulesStep()]).CleanupAsync(
            document,
            Request(user => user["onlyChangedLines"] = true, changed: [new LineRange(5, 6), new LineRange(legacyLine, legacyLine)]),
            CancellationToken.None);

        var text = await TextAsync(outcome);
        Assert.Contains("{\n            return 1;\n        }", text, StringComparison.Ordinal);
        if (!reported)
        {
            Assert.Empty(outcome.Unresolved);

            return;
        }

        var unresolved = Assert.Single(outcome.Unresolved);
        Assert.Equal("CJT0072", unresolved.Id);
        Assert.Contains("legacyValue", text.Split('\n')[unresolved.Line - 1], StringComparison.Ordinal);
    }

